#![forbid(unsafe_code)]

use buffa::Message as _;
use buffa_descriptor::generated::descriptor::FileDescriptorSet;
use sha2::{Digest as _, Sha256};
use std::path::Path;

#[allow(dead_code)]
#[path = "../codegen/emit_owned.rs"]
mod emit_owned;
#[path = "../codegen/policy.rs"]
#[allow(dead_code)]
mod policy;
#[path = "../codegen/project.rs"]
#[allow(dead_code)]
mod project;
#[path = "../codegen/schema.rs"]
#[allow(dead_code)]
mod schema;

fn hash(bytes: &[u8]) -> String {
    Sha256::digest(bytes)
        .iter()
        .map(|byte| format!("{byte:02x}"))
        .collect()
}

fn update(path: &Path, contents: &[u8], check: bool) -> std::io::Result<()> {
    if std::fs::read(path).is_ok_and(|existing| existing == contents) {
        return Ok(());
    }
    if check {
        return Err(std::io::Error::other(format!(
            "{} is out of date",
            path.display()
        )));
    }
    std::fs::write(path, contents)
}

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let arguments: Vec<_> = std::env::args().skip(1).collect();
    if !matches!(arguments.len(), 4 | 5) || (arguments.len() == 5 && arguments[4] != "--check") {
        return Err(
            "usage: protobuf_codegen DESCRIPTOR BASE_PATH RUNTIME_PATH OUTPUT [--check]".into(),
        );
    }
    let check = arguments.len() == 5;
    let descriptor = std::fs::read(&arguments[0])?;
    #[allow(clippy::disallowed_methods)]
    let descriptors = FileDescriptorSet::decode_from_slice(&descriptor)?;
    let schema = project::project(&descriptors)?;
    let generated = emit_owned::generate_private_owned(&schema, &arguments[1], &arguments[2])
        .inspect_err(|_| {
            let _ = std::fs::write(
                Path::new(&arguments[3]).with_extension("parse-failure.rs"),
                emit_owned::generate_private_owned_raw(&schema, &arguments[1], &arguments[2]),
            );
        })?;
    let source = format!("// @generated by protobuf_codegen. Do not edit.\n{generated}");
    let manifest = format!(
        "descriptor {}\nrust {}\n",
        hash(&descriptor),
        hash(source.as_bytes())
    );
    let output = Path::new(&arguments[3]);
    update(output, source.as_bytes(), check)?;
    update(
        &output.with_extension("rs.sha256"),
        manifest.as_bytes(),
        check,
    )?;
    Ok(())
}
