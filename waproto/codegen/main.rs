fn hash(bytes: &[u8]) -> String {
    Sha256::digest(bytes)
        .iter()
        .map(|byte| format!("{byte:02x}"))
        .collect()
}

fn update(path: &Path, contents: &[u8], check: bool) -> std::io::Result<()> {
    if std::fs::read(path).is_ok_and(|existing| existing == contents) {
        return Ok(());
    }
    if check {
        return Err(std::io::Error::other(format!(
            "{} is out of date",
            path.display()
        )));
    }
    std::fs::write(path, contents)
}

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let arguments: Vec<_> = std::env::args().skip(1).collect();
    if !(4..=6).contains(&arguments.len())
        || arguments[4..]
            .iter()
            .any(|flag| !matches!(flag.as_str(), "--check" | "--whatsapp"))
    {
        return Err(
            "usage: protobuf_codegen DESCRIPTOR BASE_PATH RUNTIME_PATH OUTPUT [--check] [--whatsapp]".into(),
        );
    }
    let check = arguments[4..].iter().any(|flag| flag == "--check");
    let whatsapp = arguments[4..].iter().any(|flag| flag == "--whatsapp");
    let descriptor = std::fs::read(&arguments[0])?;
    #[allow(clippy::disallowed_methods)]
    let mut descriptors = FileDescriptorSet::decode_from_slice(&descriptor)?;
    if whatsapp {
        if arguments[1] != "crate::protobuf::generated::whatsapp"
            || arguments[2] != "crate::protobuf"
        {
            return Err("WhatsApp output requires the library's fixed module paths".into());
        }
        names::apply(
            &mut descriptors,
            names::TYPES,
            names::FIELDS,
            names::ENUM_VALUES,
            names::ONEOFS,
        )?;
        retained::apply_local_fields(&mut descriptors)?;
        wallpaper::retain_fields(&mut descriptors)?;
        signal_storage::check(&names::wire_api(&descriptors))?;
    }
    let schema = project::project(&descriptors)?;
    let generated = if whatsapp {
        emit_owned::generate(&schema, &arguments[1])
    } else {
        emit_owned::generate_private_owned(&schema, &arguments[1], &arguments[2])
    }
    .inspect_err(|_| {
        let _ = std::fs::write(
            Path::new(&arguments[3]).with_extension("parse-failure.rs"),
            emit_owned::generate_private_owned_raw(&schema, &arguments[1], &arguments[2]),
        );
    })?;
    let source = format!("// @generated by protobuf_codegen. Do not edit.\n{generated}");
    let mut manifest = format!(
        "descriptor {}\nrust {}\n",
        hash(&descriptor),
        hash(source.as_bytes())
    );
    let output = Path::new(&arguments[3]);
    if whatsapp {
        let tags = retained::tags(&descriptors);
        manifest.push_str(&format!("tags {}\n", hash(tags.as_bytes())));
        update(&output.with_file_name("tags.rs"), tags.as_bytes(), check)?;
    }
    update(output, source.as_bytes(), check)?;
    update(
        &output.with_extension("rs.sha256"),
        manifest.as_bytes(),
        check,
    )?;
    Ok(())
}
