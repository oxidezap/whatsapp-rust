fn hash(bytes: &[u8]) -> String {
    Sha256::digest(bytes)
        .iter()
        .map(|byte| format!("{byte:02x}"))
        .collect()
}

fn update(path: &Path, contents: &[u8], check: bool) -> std::io::Result<()> {
    if std::fs::read(path).is_ok_and(|existing| existing == contents) {
        return Ok(());
    }
    if check {
        return Err(std::io::Error::other(format!(
            "{} is out of date",
            path.display()
        )));
    }
    std::fs::write(path, contents)
}

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let arguments: Vec<_> = std::env::args().skip(1).collect();
    if !(4..=7).contains(&arguments.len())
        || arguments[4..]
            .iter()
            .any(|flag| !matches!(flag.as_str(), "--check" | "--whatsapp" | "--update-api"))
    {
        return Err(
            "usage: protobuf_codegen DESCRIPTOR BASE_PATH RUNTIME_PATH OUTPUT [--check] [--whatsapp] [--update-api]".into(),
        );
    }
    let check = arguments[4..].iter().any(|flag| flag == "--check");
    let whatsapp = arguments[4..].iter().any(|flag| flag == "--whatsapp");
    let update_api = arguments[4..].iter().any(|flag| flag == "--update-api");
    if update_api && (!whatsapp || check) {
        return Err("--update-api requires --whatsapp and cannot be combined with --check".into());
    }
    let descriptor = std::fs::read(&arguments[0])?;
    #[allow(clippy::disallowed_methods)]
    if whatsapp {
        if arguments[1] != "crate::protobuf::generated::whatsapp"
            || arguments[2] != "crate::protobuf"
            || arguments[3] != "-"
        {
            return Err(
                "WhatsApp generation requires the library module paths and '-' output".into(),
            );
        }
        let (descriptors, source, _) = whatsapp::generate(&descriptor)?;
        let parsed = syn::parse_file(&source)?;
        let mut api = std::collections::BTreeSet::new();
        inventory::inventory_compact(&parsed.items, "whatsapp", &mut api);
        let mut api: std::collections::BTreeSet<_> = api
            .into_iter()
            .map(|entry| entry.trim_end().to_owned())
            .collect();
        api.extend(names::wire_api(&descriptors));
        let snapshot = Path::new("waproto/generated-api.snapshot");
        if update_api {
            let contents = inventory::compact_snapshot(&api)
                .into_iter()
                .collect::<Vec<_>>()
                .join("\n")
                + "\n";
            update(snapshot, contents.as_bytes(), false)?;
        } else {
            api_guard::check_api(&std::fs::read_to_string(snapshot)?, &api)?;
        }
        return Ok(());
    }
    let descriptors = FileDescriptorSet::decode_from_slice(&descriptor)?;
    let schema = project::project(&descriptors)?;
    let generated = emit_owned::generate_private_owned(&schema, &arguments[1], &arguments[2])
        .inspect_err(|_| {
            let _ = std::fs::write(
                Path::new(&arguments[3]).with_extension("parse-failure.rs"),
                emit_owned::generate_private_owned_raw(&schema, &arguments[1], &arguments[2]),
            );
        })?;
    let source = format!("// @generated by protobuf_codegen. Do not edit.\n{generated}");
    let manifest = format!(
        "descriptor {}\nrust {}\n",
        hash(&descriptor),
        hash(source.as_bytes())
    );
    let output = Path::new(&arguments[3]);
    update(output, source.as_bytes(), check)?;
    update(
        &output.with_extension("rs.sha256"),
        manifest.as_bytes(),
        check,
    )?;
    Ok(())
}
