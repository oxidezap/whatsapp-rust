    #[test]
    fn inherent_impl_bounds_cannot_restrict_existing_members() {
        let collect = |source: &str| {
            let file = syn::parse_file(source).unwrap();
            let mut api = BTreeSet::new();
            inventory(&file.items, "whatsapp", &mut api);
            api
        };
        for member in ["pub fn value(&self) {}", "pub const VALUE: u32 = 1;"] {
            let base = format!("pub struct Record<T>(T); impl<T> Record<T> {{ {member} }}");
            let baseline = collect(&base).into_iter().collect::<Vec<_>>().join("\n");
            for declaration in [
                "impl<T: Clone> Record<T>",
                "impl<T> Record<T> where T: Clone",
            ] {
                let changed = base.replace("impl<T> Record<T>", declaration);
                check_api(&baseline, &collect(&changed))
                    .expect_err("new impl bound restricts existing member availability");
            }
        }
    }

    #[test]
    fn conditional_availability_cannot_change_existing_declarations() {
        let collect = |source: &str| {
            let file = syn::parse_file(source).unwrap();
            let mut api = BTreeSet::new();
            inventory(&file.items, "whatsapp", &mut api);
            api
        };
        for source in [
            "ATTR pub struct Record { pub value: u32 }",
            "pub struct Record { ATTR pub value: u32 }",
            "ATTR pub enum Kind { Value }",
            "pub enum Kind { ATTR Value }",
            "pub struct Record; impl Record { ATTR pub fn value(&self) {} }",
            "pub struct Record; ATTR impl Record { pub fn value(&self) {} }",
            "ATTR pub mod nested { pub struct Record; }",
            "mod internal { pub struct Record; } ATTR pub use internal::Record;",
            "ATTR pub type Alias = u32;",
            "ATTR pub const VALUE: u32 = 1;",
            "pub struct Record; impl Record { ATTR pub const VALUE: u32 = 1; }",
            "pub struct Record; trait Contract { type Value; } impl Contract for Record { ATTR type Value = u32; }",
            "pub struct Record; trait Contract { const VALUE: u32; } impl Contract for Record { ATTR const VALUE: u32 = 1; }",
        ] {
            let bare = source.replace("ATTR", "");
            let baseline = collect(&bare).into_iter().collect::<Vec<_>>().join("\n");
            for attr in [
                "#[cfg(feature = \"new\")]",
                "#[cfg(target_arch = \"wasm32\")]",
                "#[cfg_attr(feature = \"new\", cfg(target_arch = \"wasm32\"))]",
            ] {
                let conditional = source.replace("ATTR", attr);
                check_api(&baseline, &collect(&conditional))
                    .expect_err("adding a condition removes an existing API");
                let frozen = collect(&conditional)
                    .into_iter()
                    .collect::<Vec<_>>()
                    .join("\n");
                check_api(&frozen, &collect(&bare))
                    .expect_err("removing a condition changes availability");
                check_api(
                    &frozen,
                    &collect(
                        &conditional
                            .replace("new", "changed")
                            .replace("wasm32", "aarch64"),
                    ),
                )
                .expect_err("changing a condition changes availability");
            }
        }
    }

    #[test]
    fn field_serialization_attributes_are_part_of_the_frozen_api() {
        let collect = |source: &str| {
            let file = syn::parse_file(source).unwrap();
            let mut api = BTreeSet::new();
            inventory(&file.items, "whatsapp", &mut api);
            api
        };
        for declaration in ["Message", "MessageView<'a>"] {
            let bare = format!("pub struct {declaration} {{ pub conversation: String }}");
            let baseline = collect(&bare).into_iter().collect::<Vec<_>>().join("\n");
            for attribute in [
                "#[serde(rename = \"original\")]",
                "#[cfg_attr(feature = \"serde\", serde(rename = \"original\"))]",
                "#[serde(skip)]",
            ] {
                let source =
                    bare.replace("pub conversation", &format!("{attribute} pub conversation"));
                check_api(&baseline, &collect(&source))
                    .expect_err("adding metadata can rename or omit a retained field");
                let frozen = collect(&source).into_iter().collect::<Vec<_>>().join("\n");
                check_api(&frozen, &collect(&bare)).expect_err("removing metadata changes JSON");
                if source.contains("original") {
                    check_api(&frozen, &collect(&source.replace("original", "changed")))
                        .expect_err("changing serialization metadata changes JSON");
                }
                let additive = source.replace(
                    "pub conversation: String",
                    "pub conversation: String, #[serde(rename = \"added\")] pub added: String",
                );
                check_api(&frozen, &collect(&additive)).expect("new fields remain additive");
                check_api(
                    &frozen,
                    &collect(
                        &source
                            .replace("pub conversation", "#[doc = \"updated\"] pub conversation"),
                    ),
                )
                .expect("documentation remains additive");
            }
        }
    }

